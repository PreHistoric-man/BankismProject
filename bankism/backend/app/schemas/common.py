"""
Common Enums and Value Types for Bankism
"""
from enum import Enum


class Verdict(str, Enum):
    APPROVE = "APPROVE"
    REVIEW = "REVIEW"
    BLOCK = "BLOCK"


class RiskLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ThreatCategory(str, Enum):
    PROMPT_INJECTION = "PROMPT_INJECTION"
    JAILBREAK_ATTEMPT = "JAILBREAK_ATTEMPT"
    MALICIOUS_PAYMENT_METADATA = "MALICIOUS_PAYMENT_METADATA"
    OBFUSCATION = "OBFUSCATION"
    AMBIGUOUS_INTENT = "AMBIGUOUS_INTENT"
    INVALID_INPUT = "INVALID_INPUT"
    NO_DETECTED_THREAT = "NO_DETECTED_THREAT"


class ProfileStatus(str, Enum):
    ESTABLISHED = "ESTABLISHED"
    INSUFFICIENT_HISTORY = "INSUFFICIENT_HISTORY"


class BehavioralPolicyAction(str, Enum):
    ALLOW_UNDER_EXISTING_POLICY = "ALLOW_UNDER_EXISTING_POLICY"
    STEP_UP_REVIEW = "STEP_UP_REVIEW"
    REQUIRE_DUAL_APPROVAL = "REQUIRE_DUAL_APPROVAL"
    HOLD_FOR_TRUSTED_REVIEW = "HOLD_FOR_TRUSTED_REVIEW"


class UserRole(str, Enum):
    CUSTOMER = "CUSTOMER"
    APPROVER = "APPROVER"
    ADMIN = "ADMIN"
